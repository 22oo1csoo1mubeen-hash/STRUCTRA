# ─── 1. Basic Generation & Loadability ────────────────────────────────────────

def test_excel_generation_produces_valid_loadable_workbook() -> None:
    """Workbook is created in memory and can be reloaded cleanly by openpyxl."""
    doc = _make_sample_metadata()
    excel_bytes = generate_document_excel_bytes(doc)

    assert isinstance(excel_bytes, bytes)
    assert len(excel_bytes) > 1000

    # Load with openpyxl
    wb = openpyxl.load_workbook(io.BytesIO(excel_bytes))
    assert "Document Report" in wb.sheetnames
    ws = wb["Document Report"]
    assert ws.max_row > 10
    assert ws.max_column >= 5


