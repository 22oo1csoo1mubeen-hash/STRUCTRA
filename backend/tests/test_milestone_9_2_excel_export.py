def test_table_header_and_total_row_styling() -> None:
    """Table headers and grand total rows have distinct styling, fills, and borders."""
    doc = _make_sample_metadata()
    excel_bytes = generate_document_excel_bytes(doc)
    wb = openpyxl.load_workbook(io.BytesIO(excel_bytes))
    ws = wb.active

    # Check table header row fill and font color
    table_header_found = False
    for row in ws.iter_rows():
        if row[1].value == "Item Description":
            table_header_found = True
            assert any(c in str(row[1].font.color.rgb) for c in ["FFFFFF", "ffffff"])
            assert "0F172A" in str(row[1].fill.start_color.rgb).upper()
            break
    assert table_header_found

    # Check Grand Total row styling
    grand_total_found = False
    for row in ws.iter_rows():
        if row[0].value == "GRAND TOTAL:":
            grand_total_found = True
            assert "FFF7ED" in str(row[0].fill.start_color.rgb).upper()
            assert row[4].font.bold is True
            assert row[4].border.bottom.style == "double"
            break
    assert grand_total_found


