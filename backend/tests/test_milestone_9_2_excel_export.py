# ─── 10. Filename Generator Tests ────────────────────────────────────────────

def test_export_filename_generation_and_sanitization() -> None:
    """Export filename uses STRUCTRA_EXPORT_<filename>.xlsx format and is sanitized."""
    # Standard original filenames
    data1 = ExportDocumentData(
        document_id="123",
        filename="receipt.jpg",
        vendor_name="D Mart",
        document_date="2026-07-29",
    )
    fn1 = generate_export_filename(data1)
    assert fn1 == "STRUCTRA_EXPORT_receipt.xlsx"
    assert not any(c in fn1 for c in '/\\:*?"<>|\x00')

    # Filename with spaces and extensions
    data2 = ExportDocumentData(
        document_id="123",
        filename="Dmart Receipt.jpeg",
        vendor_name="D Mart",
    )
    fn2 = generate_export_filename(data2)
    assert fn2 == "STRUCTRA_EXPORT_Dmart_Receipt.xlsx"

    # With illegal filesystem characters
    data3 = ExportDocumentData(
        document_id="123",
        filename="invoice/2026:08*final?.pdf",
    )
    fn3 = generate_export_filename(data3)
    assert not any(c in fn3 for c in '/\\:*?"<>|\x00')
    assert fn3.startswith("STRUCTRA_EXPORT_")
    assert fn3.endswith(".xlsx")

    # Missing filename fallback
    data4 = ExportDocumentData(
        document_id="123",
        filename="   ",
    )
    fn4 = generate_export_filename(data4)
    assert fn4 == "STRUCTRA_EXPORT_document.xlsx"


